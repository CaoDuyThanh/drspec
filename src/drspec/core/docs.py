def _insert_many(conn: duckdb.DuckDBPyConnection, sql_prefix: str, rows: List[tuple]) -> None:
    for start in range(0, len(rows), _CHUNK):
        part = rows[start : start + _CHUNK]
        marks = ", ".join("(" + ", ".join("?" for _ in part[0]) + ")" for _ in part)
        conn.execute(f"{sql_prefix} VALUES {marks}", [value for row in part for value in row])


class DocumentFrequency:
    """In how many sections each keyword occurs, over every stored section.

    Built from the database once per publish and kept up to date as documents are replaced, so ingesting
    a document costs what its own sections cost and not a pass over every section of every document."""

    def __init__(self) -> None:
        self.frequency: Dict[str, int] = {}
        self.count = 0

    @classmethod
    def from_database(cls, conn: duckdb.DuckDBPyConnection) -> "DocumentFrequency":
        table = cls()
        for (raw,) in conn.execute("SELECT keywords FROM doc_sections").fetchall():
            table.add(raw)
        return table

    def add(self, raw_keywords: Optional[str]) -> None:
        self.count += 1
        for word in _words_of(raw_keywords):
            self.frequency[word] = self.frequency.get(word, 0) + 1

    def remove(self, raw_keywords: Optional[str]) -> None:
        self.count -= 1
        for word in _words_of(raw_keywords):
            left = self.frequency.get(word, 0) - 1
            if left > 0:
                self.frequency[word] = left
            else:
                self.frequency.pop(word, None)


def _words_of(raw_keywords: Optional[str]) -> List[str]:
    try:
        return list(json.loads(raw_keywords or "[]"))
    except ValueError:
        return []


def _document_frequency(conn: duckdb.DuckDBPyConnection) -> Tuple[Dict[str, int], int]:
    table = DocumentFrequency.from_database(conn)
    return table.frequency, table.count


def _link_section(
    conn: duckdb.DuckDBPyConnection,
    section_key: str,
    file_path: str,
    title: str,
    text: str,
    spans: List[str],
    blocks: List[Dict[str, str]],
    tables: List[List[str]],
    targets: List[str],
    keyword_list: List[str],
    index: NameIndex,
    settings: Dict[str, Any],
    edited: bool,
) -> int:
    links, files = compute_links(title, text, spans, blocks, tables, targets, keyword_list, index, settings)
    existing = {
        row[0]: row[1:]
        for row in conn.execute("SELECT function_id, state, reason, code_hash_at_link, signature_at_link, previous_id, changed_at FROM doc_links WHERE section_id = ?", [section_key]).fetchall()
    }
    wanted = {link.function_id for link in links}
    # A link to a function that no longer exists is kept (it is the finding "this document names something that is gone").
    # A link that followed a rename stays until the section itself is edited: the text still says the old name.
    gone = [
        function_id for function_id, kept in existing.items()
        if function_id not in wanted and function_id in index.info and not (kept[0] == "renamed" and not edited)
    ]
    for start in range(0, len(gone), _CHUNK):
        part = gone[start : start + _CHUNK]
        conn.execute(f"DELETE FROM doc_links WHERE section_id = ? AND function_id IN ({', '.join('?' for _ in part)})", [section_key, *part])
    fresh: List[tuple] = []
    for link in links:
        code_hash, signature, _file, _name = index.info[link.function_id]
        if link.function_id in existing:
            state, reason, old_hash, old_signature, previous, changed = existing[link.function_id]
            if state == "drifted" and edited and settings.get("docs.auto_ack_on_edit", True):
                state, reason, old_hash, old_signature = "ok", "edited_after_code_change", code_hash, signature
            conn.execute(
                "UPDATE doc_links SET kind=?, confidence=?, score=?, in_code=?, state=?, reason=?, code_hash_at_link=?, signature_at_link=? WHERE section_id=? AND function_id=?",
                [link.kind, link.confidence, link.score, link.in_code, state, reason, old_hash, old_signature, section_key, link.function_id],
            )
        else:
            fresh.append((section_key, link.function_id, link.kind, link.confidence, link.score, "ok", None, link.in_code, code_hash, signature, None, None))
    _insert_many(
        conn,
        "INSERT INTO doc_links (section_id, function_id, kind, confidence, score, state, reason, in_code, code_hash_at_link, signature_at_link, previous_id, changed_at)",
        fresh,
    )
    conn.execute("DELETE FROM doc_file_links WHERE section_id = ?", [section_key])
    _insert_many(conn, "INSERT INTO doc_file_links (section_id, file_path, kind, confidence, file_hash_at_link)", [(section_key, path, "file", "EXTRACTED", None) for path in sorted(files)])
    return len(links)


def remove_document(conn: duckdb.DuckDBPyConnection, file_path: str) -> int:
    ids = [row[0] for row in conn.execute("SELECT section_id FROM doc_sections WHERE file_path = ?", [file_path]).fetchall()]
    for start in range(0, len(ids), _CHUNK):
        part = ids[start : start + _CHUNK]
        marks = ", ".join("?" for _ in part)
        conn.execute(f"DELETE FROM doc_links WHERE section_id IN ({marks})", part)
        conn.execute(f"DELETE FROM doc_file_links WHERE section_id IN ({marks})", part)
    conn.execute("DELETE FROM doc_sections WHERE file_path = ?", [file_path])
    return len(ids)


def ingest_document(
    conn: duckdb.DuckDBPyConnection,
    file_path: str,
    text: str,
    settings: Dict[str, Any],
    index: Optional[NameIndex] = None,
    frequency_table: Optional[DocumentFrequency] = None,
) -> Dict[str, int]:
    """Replace the sections and links of one document. Sections keep their identifier across edits (it comes from the
    heading path), so a section whose text did not change keeps its links and their state.

    A caller ingesting several documents passes the same `index` and `frequency_table` to each, so neither is rebuilt
    per document; the table is brought up to date with this document's old and new sections."""
    began = time.perf_counter()
    index = index or build_index(conn)
    parsed = parse_markdown(text)
    old_rows = conn.execute("SELECT section_id, text_hash, keywords FROM doc_sections WHERE file_path = ?", [file_path]).fetchall()
    old_hashes = {row[0]: row[1] for row in old_rows}
    table = frequency_table or DocumentFrequency.from_database(conn)
    frequency, documents = table.frequency, table.count

    ids = [section_id(file_path, section) for section in parsed]
    stale = [old for old in old_hashes if old not in set(ids)]
    for start in range(0, len(stale), _CHUNK):
        part = stale[start : start + _CHUNK]
        marks = ", ".join("?" for _ in part)
        conn.execute(f"DELETE FROM doc_links WHERE section_id IN ({marks})", part)
        conn.execute(f"DELETE FROM doc_file_links WHERE section_id IN ({marks})", part)
    conn.execute("DELETE FROM doc_sections WHERE file_path = ?", [file_path])

    rows: List[tuple] = []
    for position, (section, key) in enumerate(zip(parsed, ids)):
        words = section_keywords(section, frequency, max(documents, 1), int(settings.get("docs.keywords_per_section", 12)))
        rows.append(
            (
                key, file_path, section.level, section.title, section.heading_path,
                ids[section.parent_index] if section.parent_index is not None else None,
                ids[position - 1] if position > 0 else None,
                ids[position + 1] if position + 1 < len(ids) else None,
                section.start_line, section.end_line, section.text, section.text_hash,
                dumps(words), dumps(section.important), dumps(section_mentions(section)),
                json.dumps(section.code_blocks, ensure_ascii=False), json.dumps(section.front_matter, ensure_ascii=False) if section.front_matter else None,
            )
        )
    _insert_many(
        conn,
        "INSERT INTO doc_sections (section_id, file_path, level, title, heading_path, parent_id, prev_id, next_id, start_line, end_line, text, text_hash, keywords, important, mentions, code_blocks, front_matter)",
        rows,
    )
    # the words were scored against the table as it stood; now the table follows what is stored
    for _id, _hash, old_keywords in old_rows:
        table.remove(old_keywords)
    for row in rows:
        table.add(row[12])
    linked = 0
    for position, section in enumerate(parsed):
        key = ids[position]
        edited = key in old_hashes and old_hashes[key] != section.text_hash
        linked += _link_section(
            conn, key, file_path, section.title, section.text, section.inline_code, section.code_blocks, section.tables,
            [link["target"] for link in section.links], json.loads(rows[position][12]), index, settings, edited,
        )
    try:
        stat = os.stat(file_path)
        from drspec.db.queries import upsert_scanned_file

        upsert_scanned_file(conn, file_path, stat.st_mtime, stat.st_size)
    except OSError:
        pass
    if tracing.enabled():
        tracing.emit("docs", (time.perf_counter() - began) * 1000.0, kind="ingest", documents=1, sections=len(parsed), links=linked)
    return {"sections": len(parsed), "links": linked}


