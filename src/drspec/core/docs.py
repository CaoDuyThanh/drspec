"""Documents as searchable sections, linked to code without a model, and "which documents need an update?".

A document is read by `doc_parser` into sections. Each section is linked to the functions it names, in
tiers that say why (a full identifier, a qualified name, a path and a name, a bare name, a call in a code
block, an overlap of words); every link keeps the function's hash and signature as they were when it was
made. When the function changes the link is *drifted*, when it is renamed the link follows it, when it is
removed the link is kept as *removed*. `stale_findings` ranks what a person should look at.

Everything here is derived data in tables with no foreign keys (`doc_sections`, `doc_links`,
`doc_file_links`), written in the same transaction as the code it follows.
"""

