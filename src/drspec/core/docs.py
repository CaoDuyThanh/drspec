def publish_documents(
    conn: duckdb.DuckDBPyConnection,
    documents: Dict[str, str],
    gone: Iterable[str],
    settings: Dict[str, Any],
) -> Dict[str, int]:
    """Replace the sections of every document in `documents` (path -> text) and remove those of every path in `gone`,
    in the current transaction. The one place both the worker and a scan write documents, so the name index and the
    keyword table are built once however many documents there are. Call it after the code of the same publish, so a
    document sees that publish's functions."""
    gone = list(gone)
    if not documents and not gone:
        return {"documents": 0, "removed": 0}
    index = build_index(conn) if documents else None
    table = DocumentFrequency.from_database(conn) if documents else None
    for path, text in documents.items():
        ingest_document(conn, path, text, settings, index, table)
    for path in gone:
        remove_document(conn, path)
    return {"documents": len(documents), "removed": len(gone)}


def has_documents(conn: duckdb.DuckDBPyConnection) -> bool:
    return conn.execute("SELECT 1 FROM doc_links LIMIT 1").fetchone() is not None


def update_link_states(conn: duckdb.DuckDBPyConnection, carried: Optional[Dict[str, str]] = None, pairs: Optional[Iterable[Any]] = None) -> None:
    """After the code of a scan is written: links follow a renamed function, links of a changed function are
    drifted (with the reason), links of a function that is gone are kept as removed.

    `pairs` are the functions of a file that disappeared matched with those that appeared (the pairing contracts
    are carried over with, which exists for every function, not only those with a contract): a function that kept
    its name and changed its parameters (so its identifier changed) is a `signature_changed` finding, one that
    was renamed is `renamed`. Without `pairs`, every entry of `carried` is a rename."""
    if not has_documents(conn):
        return
    followed = [(pair.new_id, pair.old_id, pair.reason) for pair in (pairs or [])]
    covered = {new_id for new_id, _old, _reason in followed}
    followed += [(new_id, old_id, "renamed") for new_id, old_id in (carried or {}).items() if new_id not in covered]
    for new_id, old_id, why in followed:
        state, reason = ("drifted", "signature_changed") if why == "signature_changed" else ("renamed", "renamed")
        conn.execute(
            "UPDATE doc_links SET function_id = ?, previous_id = ?, state = ?, reason = ?, changed_at = now() "
            "WHERE function_id = ? AND section_id NOT IN (SELECT section_id FROM doc_links WHERE function_id = ?)",
            [new_id, old_id, state, reason, old_id, new_id],
        )
    conn.execute(
        """
        UPDATE doc_links SET state = 'drifted', changed_at = now(),
            reason = CASE WHEN a.signature <> doc_links.signature_at_link THEN 'signature_changed' ELSE 'body_changed' END
        FROM artifacts a
        WHERE a.function_id = doc_links.function_id AND doc_links.state = 'ok' AND a.code_hash <> doc_links.code_hash_at_link
          AND a.function_id NOT IN (SELECT function_id FROM pending_removals)
        """
    )
    conn.execute(  # a link that drifted by its body and now differs in signature too is the stronger finding
        """
        UPDATE doc_links SET reason = 'signature_changed', changed_at = now() FROM artifacts a
        WHERE a.function_id = doc_links.function_id AND doc_links.state = 'drifted' AND doc_links.reason = 'body_changed'
          AND a.signature <> doc_links.signature_at_link
        """
    )
    conn.execute(
        "UPDATE doc_links SET state = 'removed', reason = 'removed', changed_at = now() "
        "WHERE state <> 'removed' AND (function_id NOT IN (SELECT function_id FROM artifacts) OR function_id IN (SELECT function_id FROM pending_removals))"
    )


def relink_for_names(conn: duckdb.DuckDBPyConnection, names: Iterable[str], settings: Dict[str, Any]) -> int:
    """New or renamed functions: re-link only the sections that mention one of their names."""
    wanted = sorted({name for name in names if name})[:200]
    if not wanted or conn.execute("SELECT 1 FROM doc_sections LIMIT 1").fetchone() is None:
        return 0
    section_ids: Set[str] = set()
    patterns = [re.compile(r"(?<![\w])" + re.escape(name) + r"(?![\w])") for name in wanted]
    for start in range(0, len(wanted), 50):
        part = wanted[start : start + 50]
        clause = " OR ".join("contains(mentions, ?)" for _ in part)
        for key, raw in conn.execute(f"SELECT section_id, mentions FROM doc_sections WHERE {clause}", part).fetchall():
            # the SQL test is a substring test; the section must name it as a whole word
            if any(pattern.search(item) for item in json.loads(raw or "[]") for pattern in patterns):
                section_ids.add(key)
    if not section_ids:
        return 0
    index = build_index(conn)
    relinked = 0
    for key in sorted(section_ids):
        row = conn.execute("SELECT file_path, title, text, keywords FROM doc_sections WHERE section_id = ?", [key]).fetchone()
        if row is None:
            continue
        analysis = _analyse(row[2].splitlines())
        relinked += _link_section(
            conn, key, row[0], row[1], row[2], analysis["spans"], analysis["blocks"], analysis["tables"],
            [link["target"] for link in analysis["links"]], json.loads(row[3] or "[]"), index, settings, edited=False,
        )
    return len(section_ids)


