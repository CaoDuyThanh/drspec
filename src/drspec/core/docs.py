@dataclass
class NameIndex:
    by_name: Dict[str, List[str]] = field(default_factory=dict)
    by_qualified: Dict[str, List[str]] = field(default_factory=dict)
    by_id_prefix: Dict[str, List[str]] = field(default_factory=dict)
    by_word: Dict[str, Set[str]] = field(default_factory=dict)
    words: Dict[str, List[str]] = field(default_factory=dict)
    info: Dict[str, Tuple[str, str, str, str]] = field(default_factory=dict)  # id -> (code_hash, signature, file, name)
    files: Set[str] = field(default_factory=set)


def _qualified_forms(name: str) -> Set[str]:
    return {name, name.replace("::", "."), name.replace(".", "::")}


def build_index(conn: duckdb.DuckDBPyConnection) -> NameIndex:
    index = NameIndex()
    rows = conn.execute(
        "SELECT function_id, function_name, file_path, parent, code_hash, signature FROM artifacts "
        "WHERE function_id NOT IN (SELECT function_id FROM pending_removals)"
    ).fetchall()
    for function_id, name, file_path, parent, code_hash, signature in rows:
        index.info[function_id] = (code_hash, signature, file_path, name)
        index.files.add(file_path)
        index.by_name.setdefault(name, []).append(function_id)
        index.by_id_prefix.setdefault(function_id.rsplit("#", 1)[0], []).append(function_id)
        for form in _qualified_forms(qualified_name(function_id)):
            index.by_qualified.setdefault(form, []).append(function_id)
        words = split_identifier(name) + (split_identifier(parent) if parent else [])
        index.words[function_id] = split_identifier(name)
        for word in set(words):
            index.by_word.setdefault(word, set()).add(function_id)
    for key in index.by_qualified:
        index.by_qualified[key] = sorted(set(index.by_qualified[key]))
    return index


