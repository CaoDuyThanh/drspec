@dataclass
class Link:
    function_id: str
    kind: str
    confidence: str
    score: float
    in_code: bool = False


def _spread(ids: List[str], kind: str, confidence_one: str, score_one: float, in_code: bool) -> List[Link]:
    if len(ids) == 1:
        return [Link(ids[0], kind, confidence_one, score_one, in_code)]
    return [Link(function_id, kind, "AMBIGUOUS", round(1.0 / len(ids), 3), in_code) for function_id in ids]


def _paths_in(strings: Iterable[str], index: NameIndex) -> Set[str]:
    """The project files named by `strings`: exact paths, or a path that ends a known one."""
    found: Set[str] = set()
    for text in strings:
        for token in re.findall(r"[\w./\-]+", text):
            if "." not in token or token.startswith("http"):
                continue
            token = token.strip("./") if token.startswith("./") else token
            if token in index.files:
                found.add(token)
                continue
            ending = [path for path in index.files if path.endswith("/" + token)]
            if len(ending) == 1:
                found.add(ending[0])
    return found


def compute_links(
    title: str,
    text: str,
    spans: List[str],
    blocks: List[Dict[str, str]],
    tables: List[List[str]],
    link_targets: List[str],
    keywords: List[str],
    index: NameIndex,
    settings: Dict[str, Any],
) -> Tuple[List[Link], Set[str]]:
    """The links of one section to functions, and the project files it names."""
    limit = int(settings.get("docs.common_name_limit", 8))
    found: Dict[str, Link] = {}

    def offer(link: Link) -> None:
        current = found.get(link.function_id)
        if current is None or link.score > current.score:
            found[link.function_id] = link

    def usable(name: str) -> List[str]:
        ids = index.by_name.get(name, [])
        if not ids or name in COMMON_NAMES or len(ids) > limit:
            return []
        return ids

    file_mentions = _paths_in(list(spans) + link_targets + [text], index)

    # full identifiers, with or without the hash
    for token in _ID_TOKEN.findall(text) + [span for span in spans if "::" in span and _ID_TOKEN.fullmatch(span)]:
        token = token.rstrip(".")
        if token in index.info:
            offer(Link(token, "id", "EXTRACTED", 1.0))
            continue
        matching = index.by_id_prefix.get(token.split("#")[0], [])
        if matching:
            for link in _spread(matching, "id", "EXTRACTED", 1.0, False):
                offer(link)

    for raw in spans:
        span = re.sub(r"\(.*\)$", "", raw.strip())
        if not span or _ID_TOKEN.fullmatch(span):
            continue
        if "." in span or "::" in span:
            ids = index.by_qualified.get(span, [])
            if ids:
                for link in _spread(ids, "qualified", "EXTRACTED", 0.95, False):
                    offer(link)
                continue
            span = re.split(r"::|\.", span)[-1]
        if _BARE.match(span):
            ids = usable(span)
            on_the_named_file = [i for i in ids if index.info[i][2] in file_mentions]
            if on_the_named_file:
                for link in _spread(on_the_named_file, "path+name", "EXTRACTED", 0.9, False):
                    offer(link)
            elif ids:
                for link in _spread(ids, "name", "INFERRED", 0.7, False):
                    offer(link)

    for block in blocks:
        for match in _CALL.finditer(block["text"]):
            name = match.group(1)
            if name in _NOT_CALLS:
                continue
            ids = usable(name)
            on_the_named_file = [i for i in ids if index.info[i][2] in file_mentions]
            if on_the_named_file:
                ids = on_the_named_file
            if ids:
                for link in _spread(ids, "fence-call", "INFERRED", 0.6, True):
                    offer(link)

    for row in tables:
        for cell in row:
            for name in _BARE.findall(cell.strip("` ")):
                ids = usable(name)
                if ids:
                    for link in _spread(ids, "name", "INFERRED", 0.7, True):
                        offer(link)

    # an overlap of the section's words with a function's own words (at most three, weakest tier)
    section_words = set(split_identifier(title)) | {word for item in keywords for word in split_identifier(item)}
    candidates: Dict[str, int] = {}
    for word in section_words:
        for function_id in index.by_word.get(word, ()):
            candidates[function_id] = candidates.get(function_id, 0) + 1
    fuzzy = [
        (function_id, count)
        for function_id, count in candidates.items()
        if len(index.words[function_id]) >= 2 and count >= len(set(index.words[function_id])) and function_id not in found
    ]
    for function_id, _count in sorted(fuzzy, key=lambda item: (-len(index.words[item[0]]), item[0]))[:3]:
        offer(Link(function_id, "fuzzy", "INFERRED", 0.4 if len(index.words[function_id]) == 2 else 0.5))

    min_score = float(settings.get("docs.link_min_score", 0.3))
    kept = [link for link in found.values() if link.score >= min_score]
    kept.sort(key=lambda link: (-link.score, link.function_id))
    return kept[: int(settings.get("docs.max_links_per_section", 50))], file_mentions


