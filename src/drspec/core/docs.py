def priority(reason: str, confidence: str, kind: str, in_code: bool) -> float:
    weight = REASON_WEIGHT.get(reason, 1.0) * (FUZZY_WEIGHT if kind == "fuzzy" else CONFIDENCE_WEIGHT.get(confidence, 0.3))
    return round(weight * (CODE_BOOST if in_code else 1.0), 3)


def stale_findings(conn: duckdb.DuckDBPyConnection, path: Optional[str] = None, min_score: float = 0.0, limit: int = 200) -> List[Dict[str, Any]]:
    """Links whose code changed after the document was written, ranked, grouped by document and section."""
    query = (
        "SELECT s.file_path, s.section_id, s.title, s.start_line, l.function_id, l.kind, l.confidence, l.state, l.reason, l.in_code, "
        "l.signature_at_link, a.signature, l.previous_id FROM doc_links l JOIN doc_sections s ON s.section_id = l.section_id "
        "LEFT JOIN artifacts a ON a.function_id = l.function_id WHERE l.state <> 'ok'"
    )
    params: List[Any] = []
    if path:
        query += " AND s.file_path LIKE ?"
        params.append(f"{path}%")
    findings: List[Dict[str, Any]] = []
    for file_path, key, title, line, function_id, kind, confidence, state, reason, in_code, was, now, previous in conn.execute(query, params).fetchall():
        score = priority(reason or state, confidence, kind, bool(in_code))
        if score < min_score:
            continue
        finding: Dict[str, Any] = {
            "file_path": file_path, "section_id": key, "section": title, "line": line, "function_id": function_id,
            "state": state, "reason": reason, "kind": kind, "confidence": confidence, "priority": score,
        }
        if reason == "signature_changed":
            finding["signature_was"], finding["signature_now"] = was, now
        if previous:
            finding["renamed_from"] = previous
        findings.append(finding)
    findings.sort(key=lambda f: (-f["priority"], f["file_path"], f["line"], f["function_id"]))
    return findings[:limit]


def count_to_review(conn: duckdb.DuckDBPyConnection) -> int:
    if not enabled(conn):
        return 0
    return conn.execute("SELECT COUNT(DISTINCT section_id) FROM doc_links WHERE state <> 'ok'").fetchone()[0]


def sections_for(conn: duckdb.DuckDBPyConnection, function_id: str) -> List[Dict[str, Any]]:
    rows = conn.execute(
        "SELECT s.section_id, s.file_path, s.title, s.start_line, l.kind, l.confidence, l.score, l.state FROM doc_links l "
        "JOIN doc_sections s ON s.section_id = l.section_id WHERE l.function_id = ? ORDER BY l.score DESC, s.file_path, s.start_line",
        [function_id],
    ).fetchall()
    return [
        {"section_id": r[0], "file_path": r[1], "section": r[2], "line": r[3], "kind": r[4], "confidence": r[5], "score": r[6], "state": r[7]}
        for r in rows
    ]


def links_of(conn: duckdb.DuckDBPyConnection, key: str) -> Dict[str, Any]:
    row = conn.execute("SELECT section_id, file_path, title, start_line, end_line FROM doc_sections WHERE section_id = ?", [key]).fetchone()
    if row is None:
        return {}
    links = [
        {"function_id": r[0], "kind": r[1], "confidence": r[2], "score": r[3], "state": r[4], "reason": r[5]}
        for r in conn.execute("SELECT function_id, kind, confidence, score, state, reason FROM doc_links WHERE section_id = ? ORDER BY score DESC, function_id", [key]).fetchall()
    ]
    files = [r[0] for r in conn.execute("SELECT file_path FROM doc_file_links WHERE section_id = ? ORDER BY 1", [key]).fetchall()]
    return {"section_id": row[0], "file_path": row[1], "section": row[2], "start_line": row[3], "end_line": row[4], "links": links, "files": files}


def resolve_section(conn: duckdb.DuckDBPyConnection, given: str) -> Optional[str]:
    """A section identifier, or the part before the `#hash`, or `file::/Heading/Path/`."""
    if conn.execute("SELECT 1 FROM doc_sections WHERE section_id = ?", [given]).fetchone():
        return given
    rows = conn.execute(
        "SELECT section_id FROM doc_sections WHERE starts_with(section_id, ?) AND length(section_id) = ?", [given + "#", len(given) + 9]
    ).fetchall()
    return rows[0][0] if len(rows) == 1 else None


def acknowledge(conn: duckdb.DuckDBPyConnection, key: str, function_id: Optional[str] = None) -> int:
    """"Reviewed, the document is still right": the links take the code as it is now."""
    params: List[Any] = [key]
    extra = ""
    if function_id:
        extra = " AND l.function_id = ?"
        params.append(function_id)
    rows = conn.execute(
        "SELECT l.function_id, a.code_hash, a.signature FROM doc_links l JOIN artifacts a ON a.function_id = l.function_id WHERE l.section_id = ? AND l.state <> 'ok'" + extra,
        params,
    ).fetchall()
    for target, code_hash, signature in rows:
        conn.execute(
            "UPDATE doc_links SET state = 'ok', reason = 'acknowledged', code_hash_at_link = ?, signature_at_link = ?, previous_id = NULL WHERE section_id = ? AND function_id = ?",
            [code_hash, signature, key, target],
        )
    if not function_id:  # nothing to take over for a removed function: the link goes
        conn.execute("DELETE FROM doc_links WHERE section_id = ? AND state = 'removed'", [key])
    elif conn.execute("SELECT 1 FROM doc_links WHERE section_id = ? AND function_id = ? AND state = 'removed'", [key, function_id]).fetchone():
        conn.execute("DELETE FROM doc_links WHERE section_id = ? AND function_id = ?", [key, function_id])
        return len(rows) + 1
    return len(rows)


def _section_facts(conn: duckdb.DuckDBPyConnection, keys: List[str]) -> Dict[str, Dict[str, Any]]:
    """Per section: how many functions it is linked to and whether any link needs a look."""
    facts: Dict[str, Dict[str, Any]] = {}
    for start in range(0, len(keys), _CHUNK):
        part = keys[start : start + _CHUNK]
        marks = ", ".join("?" for _ in part)
        for key, count, stale in conn.execute(
            f"SELECT section_id, COUNT(*), COUNT(*) FILTER (WHERE state <> 'ok') FROM doc_links WHERE section_id IN ({marks}) GROUP BY section_id", part
        ).fetchall():
            facts[key] = {"linked_to": count, "status": "STALE" if stale else "CURRENT"}
    return facts


def search_sections(conn: duckdb.DuckDBPyConnection, query: str, limit: int = 30) -> List[Dict[str, Any]]:
    """Sections whose title, keywords or text contain every word of `query`, best first. Each carries what a person
    chooses by: its keywords, the number of functions it is linked to, whether any link needs a look
    (`CURRENT` or `STALE`) and its line range."""
    words = [word.lower() for word in re.findall(r"[A-Za-z0-9_]+", query)]
    if not words:
        return []
    rows = conn.execute("SELECT section_id, file_path, title, start_line, end_line, text, keywords FROM doc_sections").fetchall()
    results: List[Dict[str, Any]] = []
    for key, file_path, title, line, end_line, text, raw_keywords in rows:
        haystack_title, haystack_text = title.lower(), text.lower()
        keyword_list = [k.lower() for k in json.loads(raw_keywords or "[]")]
        if not all(word in haystack_title or word in haystack_text or word in keyword_list for word in words):
            continue
        score = sum(3 for word in words if word in haystack_title) + sum(2 for word in words if word in keyword_list) + sum(1 for word in words if word in haystack_text)
        results.append({"file_path": file_path, "section_id": key, "section": title, "line": line, "end_line": end_line, "keywords": keyword_list, "score": score})
    results.sort(key=lambda r: (-r["score"], r["file_path"], r["line"]))
    results = results[:limit]
    facts = _section_facts(conn, [r["section_id"] for r in results])
    for result in results:
        result.update(facts.get(result["section_id"], {"linked_to": 0, "status": "CURRENT"}))
    return results


def document_target(conn: duckdb.DuckDBPyConnection, given: str) -> Optional[Tuple[str, str]]:
    """What a command argument names among the documents: `("section", section_id)` for a section identifier (the
    `#hash` may be left out), `("document", file_path)` for the path of an indexed document, or `None`."""
    if not enabled(conn):
        return None
    if "::" in given:
        key = resolve_section(conn, given)
        return ("section", key) if key else None
    if conn.execute("SELECT 1 FROM doc_sections WHERE file_path = ? LIMIT 1", [given]).fetchone():
        return ("document", given)
    return None


def section_matches(
    conn: duckdb.DuckDBPyConnection, pattern: str, limit: int = 50, status: Optional[str] = None, path_prefix: Optional[str] = None
) -> List[Dict[str, Any]]:
    """Document sections as search results, each marked `kind: section`.

    Without a status: the sections whose title, keywords or text contain every word of `pattern`, best first.
    With `STALE`: the sections that describe code which changed since they were written, ranked, narrowed by
    `pattern` (words found in the title or a function identifier) when there is one. Documents have no other status,
    so any other status matches none."""
    if (status is not None and status != "STALE") or not enabled(conn):
        return []
    prefix = path_prefix or ""
    if status == "STALE":
        words = [word.lower() for word in re.findall(r"[A-Za-z0-9_]+", pattern or "")]
        by_section: Dict[str, Dict[str, Any]] = {}
        for finding in stale_findings(conn, path=path_prefix, limit=100000):
            text = (finding["section"] + " " + finding["function_id"]).lower()
            if not all(word in text for word in words):
                continue
            entry = by_section.get(finding["section_id"])
            if entry is None:
                entry = by_section[finding["section_id"]] = {
                    "kind": "section", "section_id": finding["section_id"], "file_path": finding["file_path"],
                    "section": finding["section"], "line": finding["line"], "status": "STALE", "priority": finding["priority"], "findings": [],
                }
            entry["findings"].append({k: v for k, v in finding.items() if k not in ("file_path", "section_id", "section", "line")})
        ranked = sorted(by_section.values(), key=lambda e: (-e["priority"], e["file_path"], e["line"]))[:limit]
        return _with_possibly_stale(conn, ranked)
    found = search_sections(conn, pattern, 100000)
    return _with_possibly_stale(conn, [{"kind": "section", **row} for row in found if row["file_path"].startswith(prefix)][:limit])


def _with_possibly_stale(conn: duckdb.DuckDBPyConnection, sections: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Mark each section whose document changed on disk since it was read (as a function's file is marked)."""
    from drspec.core.staleness import stale_paths_checked

    stale = stale_paths_checked(conn, sorted({s["file_path"] for s in sections}))
    for section in sections:
        section["possibly_stale"] = section["file_path"] in stale
    return sections


def section_dependencies(conn: duckdb.DuckDBPyConnection, kind: str, key: str) -> Dict[str, Any]:
    """`deps get` for a document: the functions and files a section (or every section of a document) describes."""
    if kind == "section":
        return {"kind": "section", **links_of(conn, key)}
    sections = [row[0] for row in conn.execute("SELECT section_id FROM doc_sections WHERE file_path = ? ORDER BY start_line", [key]).fetchall()]
    return {"kind": "document", "file_path": key, "sections": [links_of(conn, section) for section in sections]}


def section_source(conn: duckdb.DuckDBPyConnection, kind: str, key: str) -> Dict[str, Any]:
    """`source get` for a document: the text of a section, or of every section of a document."""
    columns = "section_id, file_path, title, heading_path, start_line, end_line, text"

    def row_dict(row: tuple) -> Dict[str, Any]:
        return {"section_id": row[0], "file_path": row[1], "section": row[2], "heading_path": row[3], "start_line": row[4], "end_line": row[5], "text": row[6]}

    if kind == "section":
        row = conn.execute(f"SELECT {columns} FROM doc_sections WHERE section_id = ?", [key]).fetchone()
        describes = [r[0] for r in conn.execute("SELECT function_id FROM doc_links WHERE section_id = ? ORDER BY score DESC, function_id", [key]).fetchall()]
        return {"kind": "section", **row_dict(row), "describes": describes}
    rows = conn.execute(f"SELECT {columns} FROM doc_sections WHERE file_path = ? ORDER BY start_line", [key]).fetchall()
    return {"kind": "document", "file_path": key, "sections": [row_dict(row) for row in rows]}


def undocumented(conn: duckdb.DuckDBPyConnection, limit: int = 200) -> List[Dict[str, Any]]:
    """Public functions (not tests, not starting with `_`) with no link of tier `id`, `qualified` or `path+name`."""
    if not enabled(conn):
        return []
    rows = conn.execute(
        """
        SELECT a.function_id, a.file_path, a.function_name FROM artifacts a
        WHERE NOT starts_with(a.function_name, '_') AND NOT (starts_with(a.function_name, 'test') OR a.file_path LIKE '%test%')
          AND a.function_id NOT IN (SELECT function_id FROM function_declarations WHERE definition_id IS NULL)
          AND a.function_id NOT IN (SELECT function_id FROM doc_links WHERE kind IN ('id', 'qualified', 'path+name') AND state <> 'removed')
        ORDER BY a.file_path, a.start_line LIMIT ?
        """,
        [limit],
    ).fetchall()
    return [{"function_id": r[0], "file_path": r[1], "function_name": r[2]} for r in rows]


def summary(conn: duckdb.DuckDBPyConnection) -> Dict[str, int]:
    """Counts for `status`; empty when there are no documents or they are off."""
    if not enabled(conn):
        return {}
    sections = conn.execute("SELECT COUNT(*), COUNT(DISTINCT file_path) FROM doc_sections").fetchone()
    if not sections[0]:
        return {}
    links = conn.execute("SELECT COUNT(*), COUNT(*) FILTER (WHERE state <> 'ok') FROM doc_links").fetchone()
    return {"documents": sections[1], "sections": sections[0], "links": links[0], "to_review": count_to_review(conn)}


def documented_in(conn: duckdb.DuckDBPyConnection, function_id: str, limit: int = 5) -> List[Dict[str, Any]]:
    if not enabled(conn):
        return []
    return [
        {"section_id": s["section_id"], "file_path": s["file_path"], "section": s["section"], "state": s["state"]}
        for s in sections_for(conn, function_id)[:limit]
    ]
