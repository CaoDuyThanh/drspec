from drspec.core.identity import qualified_name
from drspec.core.scanner import LANGUAGE_MAP

NEW_DOC_REASON = "new_doc"
_CHUNK = 300

#: Bare names so common that, alone, they say nothing about which function is meant.
COMMON_NAMES = frozenset("get set run main init test setup teardown start stop open close read write add remove update".split())

#: What a reason is worth when ranking a finding.
REASON_WEIGHT = {"removed": 3.0, "signature_changed": 2.0, "renamed": 2.0, "body_changed": 1.0}
CONFIDENCE_WEIGHT = {"EXTRACTED": 1.0, "INFERRED": 0.6, "AMBIGUOUS": 0.3}
FUZZY_WEIGHT = 0.2
CODE_BOOST = 1.5

_CODE_SUFFIXES = tuple(sorted(LANGUAGE_MAP, key=len, reverse=True))
_ID_TOKEN = re.compile(r"[\w./\-]+(?:" + "|".join(re.escape(s) for s in _CODE_SUFFIXES) + r")::[^\s`'\"),;]+")
_CALL = re.compile(r"(?:\b[A-Za-z_]\w*\s*(?:\.|->)\s*)?\b([A-Za-z_]\w*)\s*\(")
_BARE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_NOT_CALLS = frozenset("if for while switch return print sizeof def class elif except catch with lambda function and or not in is assert raise yield await".split())


