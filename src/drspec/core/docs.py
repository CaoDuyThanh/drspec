def extensions(settings: Dict[str, Any]) -> Tuple[str, ...]:
    return tuple("." + part.strip().lstrip(".").lower() for part in str(settings.get("docs.extensions", "md,markdown")).split(",") if part.strip())


def is_document(path: Any, settings: Dict[str, Any]) -> bool:
    return bool(settings.get("docs.enabled", False)) and str(path).lower().endswith(extensions(settings))


def readable_text(path: Any, settings: Dict[str, Any]) -> Optional[str]:
    """The text of a document, or `None` when it is too large, unreadable, or looks generated."""
    try:
        if os.path.getsize(str(path)) > int(settings.get("docs.max_file_kb", 1024)) * 1024:
            return None
        with open(str(path), "r", encoding="utf-8") as stream:
            text = stream.read()
    except (OSError, UnicodeDecodeError):
        return None
    head = text[:400].lower()
    if "auto-generated" in head or "autogenerated" in head or "do not edit" in head:
        return None
    return text


def enabled(conn: duckdb.DuckDBPyConnection) -> bool:
    """Whether documents are on (`docs.enabled`, off by default). While they are off, nothing here indexes or
    re-links a document, and the commands show no document results or counts; rows stored earlier stay."""
    from drspec.core.settings import read_all_settings

    try:
        return bool(read_all_settings(conn).get("docs.enabled", False))
    except duckdb.Error:
        return False


OFF_NOTE = "Documents are off. Turn them on with 'drspec config set docs.enabled true', then run 'drspec scan --docs-only'."


